// Helper function to get all provinces that have municipalities
export const getProvincesWithMunicipalities = (): string[] => {
  return Object.keys(philippinesMunicipalities).filter(
    (province) => philippinesMunicipalities[province].length > 0
  );
};

// Helper function to get municipalities for a specific province
export const getMunicipalitiesForProvince = (
  provinceName: string
): MunicipalityData[] => {
  return philippinesMunicipalities[provinceName] || [];
};
